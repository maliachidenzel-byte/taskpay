create table if not exists public.users (
  id text primary key,
  email text not null unique,
  password_hash text not null,
  points_available bigint not null default 0,
  points_earned bigint not null default 0,
  referrer_id text references public.users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.task_completions (
  id text primary key,
  user_id text not null references public.users(id) on delete cascade,
  task_id text not null,
  completed_day date not null,
  points integer not null,
  created_at timestamptz not null default now(),
  unique (user_id, task_id, completed_day)
);

create table if not exists public.payout_requests (
  id bigint generated by default as identity primary key,
  user_id text not null references public.users(id) on delete cascade,
  points bigint not null,
  amount numeric(12, 2) not null,
  status text not null default 'pending',
  created_at timestamptz not null default now()
);

create table if not exists public.airtel_transactions (
  id text primary key,
  user_id text not null references public.users(id) on delete cascade,
  phone text not null,
  amount integer not null,
  reference text not null unique,
  status text not null default 'INITIATED',
  date timestamptz not null default now(),
  credited boolean not null default false
);

create table if not exists public.referral_payouts (
  id text primary key,
  referrer_id text not null references public.users(id),
  referred_id text not null references public.users(id),
  amount bigint not null,
  date timestamptz not null default now(),
  notifications_seen boolean not null default false
);

drop function if exists public.complete_task(bigint, text, date, integer);
create or replace function public.complete_task(p_user_id text, p_task_id text, p_completed_day date, p_points integer)
returns text
language plpgsql
as $$
declare
  completion_id text := gen_random_uuid()::text;
begin
  insert into public.task_completions (id, user_id, task_id, completed_day, points)
  values (completion_id, p_user_id, p_task_id, p_completed_day, p_points);

  update public.users
  set points_available = points_available + p_points,
      points_earned = points_earned + p_points
  where id = p_user_id;

  return completion_id;
end;
$$;

drop function if exists public.request_payout(bigint, bigint, numeric);
create or replace function public.request_payout(p_user_id text, p_points bigint, p_amount numeric)
returns jsonb
language plpgsql
as $$
declare
  payout_id bigint;
begin
  update public.users
  set points_available = points_available - p_points
  where id = p_user_id and points_available >= p_points;

  if not found then
    return jsonb_build_object('error', 'INSUFFICIENT_POINTS');
  end if;

  insert into public.payout_requests (user_id, points, amount)
  values (p_user_id, p_points, p_amount)
  returning id into payout_id;

  return jsonb_build_object('payoutId', payout_id);
end;
$$;

create or replace function public.credit_airtel_payment(p_reference text)
returns jsonb
language plpgsql
as $$
declare
  payment public.airtel_transactions%rowtype;
  referred_user public.users%rowtype;
  prior_successes integer;
  bonus_points bigint := 0;
  referral_payout_id text;
begin
  select * into payment
  from public.airtel_transactions
  where reference = p_reference
  for update;

  if not found then
    return null;
  end if;
  if payment.credited then
    return jsonb_build_object('status', 'SUCCESS', 'referralBonus', null);
  end if;

  perform 1 from public.users where id = payment.user_id for update;

  select count(*) into prior_successes
  from public.airtel_transactions
  where user_id = payment.user_id
    and status = 'SUCCESS'
    and reference <> p_reference;

  update public.airtel_transactions
  set status = 'SUCCESS', credited = true
  where id = payment.id;
  update public.users
  set points_available = points_available + payment.amount
  where id = payment.user_id;

  select * into referred_user from public.users where id = payment.user_id;
  if prior_successes = 0 and referred_user.referrer_id is not null then
    bonus_points := floor(payment.amount * 0.3);
    if bonus_points > 0 then
      referral_payout_id := gen_random_uuid()::text;
      update public.users
      set points_available = points_available + bonus_points
      where id = referred_user.referrer_id;
      insert into public.referral_payouts (id, referrer_id, referred_id, amount)
      values (referral_payout_id, referred_user.referrer_id, referred_user.id, bonus_points);
    end if;
  end if;

  return jsonb_build_object(
    'status', 'SUCCESS',
    'referralBonus', case when bonus_points > 0 then jsonb_build_object('amount', bonus_points, 'points', bonus_points) else null end
  );
end;
$$;

drop function if exists public.claim_referral_notifications(bigint);
create or replace function public.claim_referral_notifications(p_referrer_id text)
returns table (amount bigint)
language sql
as $$
  with claimed as (
    select id
    from public.referral_payouts
    where referrer_id = p_referrer_id and notifications_seen = false
    for update skip locked
  )
  update public.referral_payouts payout
  set notifications_seen = true
  from claimed
  where payout.id = claimed.id
  returning payout.amount;
$$;

